"""Render a room's stroke history to a snapshot image on the server.

The browser produces snapshots during normal use, but that is no help for a room
that was generated by the seeder: joining it to create the first snapshot would
require the very full replay the snapshot is meant to avoid. This script closes
that loop, and it is also how snapshotting would be done in production, where you
would not want to trust a client to rasterise authoritative state.

    python scripts/make_snapshot.py --room LNCSJ5
    python scripts/make_snapshot.py --all
"""

import argparse
import asyncio
import base64
import io
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from PIL import Image, ImageDraw  # noqa: E402

from app.db import ROOMS, close, db  # noqa: E402
from app.repositories import snapshots as snap_repo  # noqa: E402
from app.repositories import strokes as strokes_repo  # noqa: E402

LOGICAL_W, LOGICAL_H = 1600, 900
SUPERSAMPLE = 2  # draw large, downscale once: cheap antialiasing


def render(strokes: list[dict], background: str = "#ffffff") -> Image.Image:
    scale = SUPERSAMPLE
    img = Image.new("RGB", (LOGICAL_W * scale, LOGICAL_H * scale), background)
    draw = ImageDraw.Draw(img)

    for stroke in strokes:
        style = stroke.get("style", {})
        # Flattening to an opaque raster means an eraser is simply the background
        # colour. The cut-out blend only matters while strokes are still separate.
        colour = background if style.get("blend") == "destination-out" else style.get("color", "#111827")
        width = max(int(round(style.get("width", 3) * scale)), 1)
        tool = stroke.get("tool", "pen")
        pts = stroke.get("points")
        geo = stroke.get("geometry")

        try:
            if tool in ("pen", "eraser") and pts:
                xy = [(p["x"] * scale, p["y"] * scale) for p in pts]
                if len(xy) == 1:
                    r = width / 2
                    draw.ellipse([xy[0][0] - r, xy[0][1] - r, xy[0][0] + r, xy[0][1] + r], fill=colour)
                else:
                    draw.line(xy, fill=colour, width=width, joint="curve")
            elif tool == "text" and stroke.get("text") and pts:
                draw.text((pts[0]["x"] * scale, pts[0]["y"] * scale), stroke["text"], fill=colour)
            elif geo:
                x0, y0 = geo["x"] * scale, geo["y"] * scale
                x1, y1 = (geo["x"] + geo["w"]) * scale, (geo["y"] + geo["h"]) * scale
                if tool == "line":
                    draw.line([(x0, y0), (x1, y1)], fill=colour, width=width)
                else:
                    box = [min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1)]
                    if tool == "rect":
                        draw.rectangle(box, outline=colour, width=width)
                    elif tool == "ellipse":
                        draw.ellipse(box, outline=colour, width=width)
        except Exception:
            # One malformed document must not abandon a 40,000-stroke render.
            continue

    return img.resize((LOGICAL_W, LOGICAL_H), Image.LANCZOS)


async def snapshot_room(room: dict) -> dict | None:
    room_id = room["_id"]
    max_seq = await strokes_repo.max_seq(room_id)
    if max_seq == 0:
        return None

    started = time.perf_counter()
    strokes = await strokes_repo.list_strokes(room_id, after_seq=0)
    fetch_ms = (time.perf_counter() - started) * 1000

    started = time.perf_counter()
    img = render(strokes, room.get("background", "#ffffff"))
    render_ms = (time.perf_counter() - started) * 1000

    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    data_url = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

    saved = await snap_repo.create_snapshot(room_id, max_seq, data_url, len(strokes))
    await snap_repo.prune_snapshots(room_id)

    return {
        "code": room["code"],
        "strokes": len(strokes),
        "upToSeq": max_seq,
        "pngKB": round(len(buf.getvalue()) / 1024, 1),
        "dataUrlKB": round(len(data_url) / 1024, 1),
        "fetchMs": round(fetch_ms),
        "renderMs": round(render_ms),
        "id": str(saved["_id"]),
    }


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--room", help="room code")
    ap.add_argument("--all", action="store_true", help="snapshot every room")
    ap.add_argument("--min-strokes", type=int, default=500,
                    help="skip rooms smaller than this; a snapshot would cost more than it saves")
    args = ap.parse_args()

    if not args.room and not args.all:
        ap.error("pass --room CODE or --all")

    query = {"code": args.room.upper()} if args.room else {}
    rooms = [r async for r in db()[ROOMS].find(query).sort("strokeCount", -1)]

    for room in rooms:
        if args.all and (room.get("strokeCount") or 0) < args.min_strokes:
            print(f"{room['code']}: skipped ({room.get('strokeCount', 0)} strokes, "
                  f"below --min-strokes {args.min_strokes})")
            continue
        result = await snapshot_room(room)
        if not result:
            print(f"{room['code']}: nothing to snapshot")
            continue
        print(
            f"{result['code']}: rendered {result['strokes']:,} strokes up to seq "
            f"{result['upToSeq']:,} -> {result['pngKB']:.0f} KB PNG "
            f"({result['dataUrlKB']:.0f} KB as a data URL); "
            f"fetch {result['fetchMs']} ms, render {result['renderMs']} ms"
        )

    await close()


if __name__ == "__main__":
    asyncio.run(main())
